/* ---- drawing helpers ---- */

static inline uint32_t col(SplashFB *s, uint8_t r, uint8_t g, uint8_t b)
{
	return ((uint32_t)r << s->r_shift) |
	       ((uint32_t)g << s->g_shift) |
	       ((uint32_t)b << s->b_shift);
}

static void fill_rect(SplashFB *s, int x, int y, int w, int h, uint32_t c)
{
	for (int j = y; j < y + h; j++)
		for (int i = x; i < x + w; i++)
			s->fb[j * s->pitch4 + i] = c;
}

static void draw_char(SplashFB *s, int x, int y, char ch,
                       uint32_t color, int scale)
{
	if (ch < 32 || ch > 126)
		return;
	const uint8_t *glyph = font8x8[ch - 32];
	for (int row = 0; row < 8; row++) {
		uint8_t bits = glyph[row];
		for (int c = 0; c < 8; c++) {
			if (bits & (0x80 >> c))
				fill_rect(s, x + c * scale, y + row * scale,
				          scale, scale, color);
		}
	}
}

static int str_width(const char *str, int scale)
{
	int n = 0;
	while (str[n])
		n++;
	return n > 0 ? n * 9 * scale - scale : 0;
}

static void draw_str(SplashFB *s, int x, int y, const char *str,
                      uint32_t color, int scale)
{
	while (*str) {
		draw_char(s, x, y, *str, color, scale);
		x += 9 * scale;
		str++;
	}
}

static void draw_str_centered(SplashFB *s, int y, const char *str,
                               uint32_t color, int scale)
{
	int sw = str_width(str, scale);
	draw_str(s, (s->width - sw) / 2, y, str, color, scale);
}


int splash_screen(SplashFB *s)
{
	int w = s->width;
	int h = s->height;

	uint32_t bg      = col(s, 15, 15, 35);
	uint32_t white   = col(s, 255, 255, 255);
	uint32_t gray    = col(s, 160, 170, 200);
	uint32_t dim     = col(s, 80, 85, 120);
	uint32_t box_bg  = col(s, 40, 42, 70);
	uint32_t box_brd = col(s, 70, 75, 110);
	uint32_t sel_bg  = col(s, 50, 110, 210);
	uint32_t sel_brd = col(s, 80, 160, 255);

	fill_rect(s, 0, 0, w, h, bg);

	int title_y = h * 20 / 100;
	draw_str_centered(s, title_y, "IOS", white, 6);

	int line_y = title_y + 6 * 8 + 15;
	int line_w = 220;
	fill_rect(s, (w - line_w) / 2, line_y, line_w, 2, dim);

	/* mission */
	draw_str_centered(s, line_y + 25, "Select Node ID", gray, 2);

	/* nodes */
	int box_w = 50, box_h = 50, gap = 15, brd = 3;
	int total_w = 8 * box_w + 7 * gap;
	int bx0 = (w - total_w) / 2;
	int by0 = h * 48 / 100;

	/* instrucitons */
	draw_str_centered(s, by0 + box_h + brd + 25,
	                  "Arrow keys to select, ENTER to confirm", dim, 1);

	int sel = 0;

	for (;;) {
		/* boxes */
		for (int i = 0; i < 8; i++) {
			int bx = bx0 + i * (box_w + gap);
			uint32_t bbg  = (i == sel) ? sel_bg  : box_bg;
			uint32_t bbrd = (i == sel) ? sel_brd : box_brd;

			fill_rect(s, bx - brd, by0 - brd,
			          box_w + 2 * brd, box_h + 2 * brd, bbrd);
			fill_rect(s, bx, by0, box_w, box_h, bbg);

			int cs = 3;
			int cx = bx + (box_w - 8 * cs) / 2;
			int cy = by0 + (box_h - 8 * cs) / 2;
			draw_char(s, cx, cy, '0' + i, white, cs);
		}

		int ch = getCharEx();
		if (ch == KEY_LEFT  && sel > 0) sel--;
		if (ch == KEY_RIGHT && sel < 7) sel++;
		if (ch == '\n') break;
	}

	fill_rect(s, 0, 0, w, h, 0);
	return sel;
}
